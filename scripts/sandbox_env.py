#!/usr/bin/env python3
"""Workspace environment for a repository: detection, sandbox init, rig env.

Rig never edits the project's own devcontainer files. For a folder with no
configuration it stores the config dc-cli generates under .rig/sandbox/override.json
and passes it with --override-config. Container lifecycle is separate from the
worker sandbox provider: nothing here changes where workers run.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import dc_client  # noqa: E402
import harness  # noqa: E402

OVERRIDE = Path(".rig") / "sandbox" / "override.json"
_COMPOSE = ("compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml")


def detect_kind(repo: Path) -> str:
    """devcontainer | compose | none, from the project's own files only."""
    repo = Path(repo)
    if (repo / ".devcontainer.json").is_file() or (repo / ".devcontainer" / "devcontainer.json").is_file():
        return "devcontainer"
    folder = repo / ".devcontainer"
    if folder.is_dir() and any((child / "devcontainer.json").is_file() for child in folder.iterdir() if child.is_dir()):
        return "devcontainer"
    if any((repo / name).is_file() for name in _COMPOSE):
        return "compose"
    return "none"


def override_path(repo: Path) -> Path:
    return Path(repo) / OVERRIDE


def init_sandbox(repo: Path, *, force: bool = False) -> dict:
    """Detect the workspace kind and, for a folder with no config, store a generated one."""
    repo = Path(repo).resolve()
    harness.assert_project_enabled(repo)
    kind = detect_kind(repo)
    path = override_path(repo)
    report = {"kind": kind, "override": str(path), "wrote": False, "note": ""}
    if kind != "none":
        report["note"] = f"{kind} found; the project's own files are used as they are"
        return report
    if path.is_file() and not force:
        report["note"] = "kept existing override; pass --force to regenerate"
        return report
    done = dc_client.run(["try", "--print"], repo)
    if done.returncode != 0:
        detail = (done.stderr or done.stdout).strip().splitlines()
        raise dc_client.DcError(f"dc try --print failed ({done.returncode}): {detail[-1] if detail else 'no output'}")
    try:
        generated = json.loads(done.stdout)
    except ValueError as error:
        raise dc_client.DcError("dc try --print did not print a JSON config") from error
    if not isinstance(generated, dict) or not generated:
        raise dc_client.DcError("dc try --print printed an empty or non-object config")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(generated, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, path)
    report.update(wrote=True, note="generated by dc try --print; the project's own files were not touched")
    return report


def _mount(source, readonly: bool = True) -> str:
    """A bind mount at the SAME path inside the container (Rig never translates paths)."""
    return f"source={source},target={source},type=bind" + (",readonly" if readonly else "")


def effective_config(repo: Path, generated: dict, credentials: dict, runtime: Path, home: Path) -> dict:
    """The generated config plus what container mode needs: the repository mounted at its own
    path, the Rig runtime read-only, and the login directories of workers opted in with mount-ro."""
    import container_modes
    repo = str(Path(repo).resolve())
    config = dict(generated)
    config["workspaceMount"] = _mount(repo, readonly=False)
    config["workspaceFolder"] = repo
    mounts = [m for m in config.get("mounts", []) if isinstance(m, (str, dict))]
    wanted = [_mount(runtime)]
    for worker in sorted(credentials):
        if credentials[worker] != "mount-ro":
            continue
        for relative in container_modes.mode(worker).get("credential_paths", []):
            if (Path(home) / relative).exists():  # never mount what is not there
                wanted.append(_mount(Path(home) / relative))
    config["mounts"] = mounts + [m for m in wanted if m not in mounts]
    return config


def effective_path(repo: Path) -> Path:
    return Path(repo) / ".rig" / "sandbox" / "effective.json"


def write_effective(repo: Path) -> Path:
    """Regenerate effective.json from override.json and the current [sandbox.workers] choices."""
    generated = json.loads(override_path(repo).read_text())
    if not isinstance(generated, dict):
        raise dc_client.DcError(f"{override_path(repo)} is not a JSON object; run rig init --sandbox --force")
    config = harness.parse_harness(harness.harness_path(repo))["sandbox"]
    from sandbox_container import RUNTIME
    merged = effective_config(repo, generated, config["credentials"], RUNTIME, Path(os.path.expanduser("~")))
    path = effective_path(repo)
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(merged, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, path)
    return path


def _lifecycle(repo: Path, verb: str) -> int:
    repo = Path(repo).resolve()
    harness.assert_project_enabled(repo)
    args = [verb]
    path = override_path(repo)
    if verb == "up" and detect_kind(repo) == "none" and path.is_file():
        args += ["--override-config", str(write_effective(repo))]
    elif verb == "up" and harness.parse_harness(harness.harness_path(repo))["sandbox"]["provider"] == "devcontainer":
        print("rig env: the project's own container config is used as it is; container mode needs it to mount the "
              "repository and the Rig runtime at the same paths (rig doctor --workspace checks)", file=sys.stderr)
    done = dc_client.run(args, repo, timeout=900 if verb == "up" else 120, stream=True)
    return done.returncode


def env_up(repo: Path) -> int:
    return _lifecycle(repo, "up")


def env_down(repo: Path) -> int:
    return _lifecycle(repo, "down")


def env_status(repo: Path) -> dict:
    """Facts only. Container rows are dc's own JSON, matched to this repo by path."""
    repo = Path(repo).resolve()
    binary = dc_client.dc_binary()
    found = dc_client.version(binary) if binary else ""
    pin = dc_client.pinned_version()
    status = {
        "kind": detect_kind(repo),
        "override": {"path": str(override_path(repo)), "exists": override_path(repo).is_file()},
        "dc": {"found": bool(binary), "path": binary, "version": found, "pin": pin,
               "pin_state": dc_client.pin_state(found, pin)},
        "containers": [], "matched_by": "path", "error": "",
    }
    if not binary:
        status["error"] = "dc-cli is not installed"
        return status
    try:
        listing = dc_client.run_json(["ls", "--json"], repo)
    except dc_client.DcError as error:
        status["error"] = str(error)
        return status
    rows = listing if isinstance(listing, list) else dc_client.pick(listing, "containers", "items", default=[])
    needle = str(repo)
    status["containers"] = [row for row in rows or [] if isinstance(row, dict) and needle in json.dumps(row)]
    return status


def format_status(status: dict) -> str:
    dc = status["dc"]
    lines = [f"workspace   {status['kind']}",
             f"override    {'present' if status['override']['exists'] else 'none'}  {status['override']['path']}",
             f"dc-cli      {dc['version'] or ('not installed' if not dc['found'] else 'unknown version')}"
             f"  pin {dc['pin'] or 'none'} ({dc['pin_state']})"]
    for row in status["containers"]:
        name = dc_client.pick(row, "name", "id", "container", default="container")
        state = dc_client.pick(row, "state", "status", default="unknown")
        lines.append(f"container   {name}  {state}")
    if not status["containers"] and not status["error"]:
        lines.append("container   none found for this repository")
    if status["error"]:
        lines.append(f"note        {status['error']}")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="rig env", description="Workspace environment through dc-cli")
    parser.add_argument("command", choices=["init", "up", "down", "status"])
    parser.add_argument("--repo", default="")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--force", action="store_true", help="init: regenerate an existing override")
    args = parser.parse_args(argv)
    try:
        import jobs
        repo = jobs.repo_root(args.repo or None)
        if args.command == "init":
            report = init_sandbox(repo, force=args.force)
            print(json.dumps(report, indent=2) if args.json else
                  f"sandbox: {report['kind']}" + (f" · wrote {report['override']}" if report["wrote"] else "") + f"\n{report['note']}")
            return 0
        if args.command == "status":
            status = env_status(repo)
            print(json.dumps(status, indent=2) if args.json else format_status(status))
            return 0
        return env_up(repo) if args.command == "up" else env_down(repo)
    except (dc_client.DcError, ValueError, SystemExit) as error:
        print(f"rig env: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
